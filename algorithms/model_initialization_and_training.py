def evaluate_checkpoint(
    name,
    path,
    seed_idx,
    X,
    Y
):

    model = load_model_strict(path)

    y_true = np.argmax(Y, axis=1)

    probs = model.predict(
        X,
        batch_size=16,
        verbose=0
    )

    y_pred = np.argmax(
        probs,
        axis=1
    )

    rep = classification_report(
        y_true,
        y_pred,
        labels=range(N_CLASSES),
        target_names=TARGET_CLASSES,
        output_dict=True,
        zero_division=0
    )

    lat = benchmark_latency(
        model,
        X[:1]
    )

    row = {
        "Model": name,
        "Seed": seed_idx,
        "Checkpoint": os.path.basename(path),
        "Accuracy": accuracy_score(
            y_true,
            y_pred
        ),
        "Macro Precision": rep["macro avg"]["precision"],
        "Macro Recall": rep["macro avg"]["recall"],
        "Macro F1": rep["macro avg"]["f1-score"],
        "AUC-ROC (macro)": roc_auc_score(
            Y,
            probs,
            multi_class="ovr",
            average="macro"
        ),
        "Latency mean (ms)": lat.mean(),
        "Latency SD (ms)": lat.std(),
        "Latency median (ms)": np.median(lat),
        "Latency p95 (ms)": np.percentile(lat, 95),
        "Params (M)": model.count_params() / 1e6,
        "Size, optimizer-free (MB)": stripped_size_mb(model),
        "Checkpoint file (MB)": os.path.getsize(path) / 1024 ** 2,
        "FLOPs (G)": count_flops(model) / 1e9
    }

    per_class = pd.DataFrame(rep).T.loc[
        TARGET_CLASSES,
        [
            "precision",
            "recall",
            "f1-score",
            "support"
        ]
    ]

    per_class.insert(
        0,
        "Seed",
        seed_idx
    )

    per_class.insert(
        0,
        "Model",
        name
    )

    cm = confusion_matrix(
        y_true,
        y_pred,
        labels=range(N_CLASSES)
    )

    plt.figure(figsize=(6, 5))

    sns.heatmap(
        cm,
        annot=True,
        fmt="d",
        cmap="Blues",
        xticklabels=TARGET_CLASSES,
        yticklabels=TARGET_CLASSES
    )

    plt.title(
        f"Confusion Matrix: {name} (seed {seed_idx})"
    )

    plt.ylabel("True Label")
    plt.xlabel("Predicted Label")

    plt.tight_layout()

    plt.savefig(
        os.path.join(
            OUT_DIR,
            f"cm_{name.replace(' ', '_')}_seed{seed_idx}.png"
        ),
        dpi=200
    )

    plt.close()

    wrong = np.where(
        y_true != y_pred
    )[0]

    mis = pd.DataFrame({
        "Model": name,
        "Seed": seed_idx,
        "test_index": wrong,
        "true": [
            TARGET_CLASSES[i]
            for i in y_true[wrong]
        ],
        "pred": [
            TARGET_CLASSES[i]
            for i in y_pred[wrong]
        ],
        "confidence": probs[
            wrong,
            y_pred[wrong]
        ],
        "file": (
            [
                TEST_FILEPATHS[i]
                for i in wrong
            ]
            if TEST_FILEPATHS is not None
            else None
        )
    })

    del model

    tf.keras.backend.clear_session()

    return (
        row,
        per_class,
        mis,
        y_pred,
        lat
    )


