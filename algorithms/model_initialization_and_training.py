def _macro_f1(y, p):

    return f1_score(
        y,
        p,
        average="macro",
        zero_division=0
    )


def _resample_indices(
    n,
    rng,
    groups=None,
    idx_by_group=None,
    unique_groups=None
):

    if groups is None:
        return rng.integers(0, n, n)

    chosen = rng.choice(
        unique_groups,
        len(unique_groups),
        replace=True
    )

    return np.concatenate(
        [
            idx_by_group[g]
            for g in chosen
        ]
    )


def _group_index(groups):

    if groups is None:
        return None, None

    groups = np.asarray(groups)

    ug = np.unique(groups)

    return ug, {
        g: np.where(groups == g)[0]
        for g in ug
    }


def bootstrap_ci(
    y,
    p,
    n=N_BOOTSTRAP,
    groups=None,
    seed=42
):

    rng = np.random.default_rng(seed)

    ug, ibg = _group_index(groups)

    acc = []
    f1 = []

    for _ in range(n):

        i = _resample_indices(
            len(y),
            rng,
            groups,
            ibg,
            ug
        )

        acc.append(
            accuracy_score(
                y[i],
                p[i]
            )
        )

        f1.append(
            _macro_f1(
                y[i],
                p[i]
            )
        )

    return (
        np.percentile(acc, [2.5, 97.5]),
        np.percentile(f1, [2.5, 97.5])
    )


def paired_bootstrap_diff(
    y,
    pa,
    pb,
    n=N_BOOTSTRAP,
    groups=None,
    seed=42
):

    rng = np.random.default_rng(seed)

    ug, ibg = _group_index(groups)

    diffs = []

    for _ in range(n):

        i = _resample_indices(
            len(y),
            rng,
            groups,
            ibg,
            ug
        )

        diffs.append(
            _macro_f1(
                y[i],
                pa[i]
            )
            -
            _macro_f1(
                y[i],
                pb[i]
            )
        )

    return (
        np.percentile(diffs, [2.5, 97.5]),
        float(np.mean(diffs))
    )


