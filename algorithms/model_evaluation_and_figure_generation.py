def sheet_to_csv(title, out_csv):
    # Drive names have no ".gsheet" extension: it is only how the mount displays them.
    hits = [f for f in gc.list_spreadsheet_files(title=title) if f["name"] == title]
    if not hits:
        raise FileNotFoundError(f"No spreadsheet named {title!r} visible to this account")
    hits.sort(key=lambda f: f.get("modifiedTime", ""), reverse=True)
    if len(hits) > 1:
        print(f"  note: {len(hits)} sheets named {title!r}; using newest ({hits[0].get('modifiedTime')})")
    ws = gc.open_by_key(hits[0]["id"]).sheet1
    vals = ws.get_all_values(value_render_option="UNFORMATTED_VALUE")   # full precision
    df = pd.DataFrame(vals[1:], columns=vals[0])
    for c in df.columns:
        if c != "stage":
            df[c] = pd.to_numeric(df[c], errors="coerce")
    df.to_csv(out_csv, index=False)
    return df

