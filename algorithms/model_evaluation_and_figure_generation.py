# 2. Grad-CAM computation (Bulletproof Graph-based method)
def compute_gradcam(img_tensor, model):
    # Find the Global Average Pooling layer
    gap_layer = None
    for layer in model.layers:
        if isinstance(layer, tf.keras.layers.GlobalAveragePooling2D):
            gap_layer = layer
            break

    if gap_layer is None:
        raise ValueError("Could not find GlobalAveragePooling2D layer in the model.")

    # Create a sub-model that outputs both the 4D feature map (the input to GAP) and the final predictions
    grad_model = tf.keras.Model(
        inputs=model.inputs,
        outputs=[gap_layer.input, model.output]
    )

    with tf.GradientTape() as tape:
        conv_out, preds = grad_model(img_tensor, training=False)
        pred_idx = tf.argmax(preds[0])
        loss = preds[:, pred_idx]

    # Compute gradients of the predicted class with respect to the feature map
    grads = tape.gradient(loss, conv_out)

    # Pool gradients over the spatial dimensions
    pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))

    # Weight the feature map by the pooled gradients
    heatmap = tf.reduce_sum(tf.multiply(pooled_grads, conv_out[0]), axis=-1)

    # Apply ReLU (only keep positive influences) and normalize
    heatmap = tf.maximum(heatmap, 0)
    max_val = tf.math.reduce_max(heatmap)
    if max_val > 0:
        heatmap /= max_val

    return heatmap.numpy(), int(pred_idx.numpy())

